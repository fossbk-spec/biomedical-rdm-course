#!/usr/bin/env python3
"""Sync mini-course pages and manifest-driven textbook pages from the source repo."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


MARKER = re.compile(r"^<!-- page: (?P<path>[^>]+?) -->\s*$", re.MULTILINE)
GENERATED = "<!-- generated by scripts/sync_from_source.py from {source}; do not edit -->\n"


def parse_pages(source: Path) -> dict[str, str]:
    text = source.read_text(encoding="utf-8")
    matches = list(MARKER.finditer(text))
    if not matches:
        raise ValueError("no page markers found")
    pages: dict[str, str] = {}
    for index, match in enumerate(matches):
        page_path = match.group("path").strip().replace("/", "\\")
        if page_path in pages:
            raise ValueError(f"duplicate page marker: {page_path}")
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        content = text[match.end():end].lstrip("\r\n")
        pages[page_path] = content.rstrip() + "\n"
    return pages


def parse_front_matter(text: str) -> tuple[str, str]:
    if not text.startswith("---\n"):
        return "", text
    end = text.find("\n---", 4)
    if end < 0:
        return "", text
    closing = end + len("\n---")
    return text[:closing] + "\n", text[closing:].lstrip("\r\n")


def convert_text(text: str, source_rel: str, target_rel: str, ref_targets: dict[str, str]) -> str:
    front_matter, body = parse_front_matter(text)
    # Quarto-only keys are not valid VitePress front matter. Keep public metadata only.
    if front_matter:
        allowed = {"title", "subtitle", "author", "orcid", "date", "reviewed", "next_review"}
        lines = front_matter.splitlines()
        kept = [lines[0]]
        for line in lines[1:-1]:
            key = line.split(":", 1)[0].strip()
            if key in allowed:
                kept.append(line)
        kept.append("---")
        front_matter = "\n".join(kept) + "\n"

    def ref_replace(match: re.Match[str]) -> str:
        keys = [k.strip() for k in match.group(1).split(";")]
        nums = [k.strip().lstrip("@").removeprefix("ref_").lstrip("0") or "0" for k in keys]
        return "; ".join(f"[{n}](/course/book/references#ref-{n})" for n in nums)

    body = re.sub(r"\[@([^]]+)\]", ref_replace, body)
    for source, target in sorted(ref_targets.items(), key=lambda item: -len(item[0])):
        filename = source.rsplit("/", 1)[-1]
        target_url = "/" + target.removesuffix(".md")
        body = body.replace(source, target_url)
        body = body.replace(f"../appendices/{filename}", target_url)
        body = body.replace(f"../chapters/{filename}", target_url)
        body = body.replace(f"../{filename}", target_url)
        body = body.replace(f"({filename}", f"({target_url}")
    # Source-relative links not represented by the manifest become stable source links.
    body = re.sub(r"\]\((\.\./(?:chapters|appendices|legal-verification)\.md)(#[^)]*)?\)",
                  lambda m: "](https://github.com/fossbk-spec/biomedical-rdm/blob/main/docs/"
                            + m.group(1).removeprefix("../") + (m.group(2) or "") + ")", body)
    return GENERATED.format(source=source_rel) + front_matter + body.rstrip() + "\n"


def load_manifest(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def render_bib(text: str, audit_path: Path) -> str:
    audit: dict[str, str] = {}
    if audit_path.is_file():
        for line in audit_path.read_text(encoding="utf-8").splitlines()[1:]:
            fields = [part.strip().strip('"') for part in line.split(",")]
            if len(fields) >= 3:
                audit[fields[1]] = fields[2]
    entries = re.split(r"(?=^@)", text, flags=re.MULTILINE)
    out = [GENERATED.format(source="references/references.bib"),
           "# Danh mục tham khảo", "",
           "> Trạng thái là cờ trong `citation-audit.csv`; các mục `VERIFIED_UNAUDITED` chưa được audit độc lập.", ""]
    for entry in entries:
        match = re.search(r"^@\w+\{([^,]+),", entry, re.MULTILINE)
        if not match:
            continue
        key = match.group(1).strip()
        def field(name: str) -> str:
            found = re.search(rf"^\s*{name}\s*=\s*\{{(.*?)\}}\s*,?\s*$", entry, re.MULTILINE | re.DOTALL)
            return re.sub(r"\s+", " ", found.group(1)).strip() if found else ""
        number = key.removeprefix("ref_").lstrip("0") or "0"
        author, year, title = field("author"), field("year"), field("title")
        venue = field("journal") or field("publisher") or field("booktitle")
        doi, url = field("doi"), field("url")
        links = f" DOI: https://doi.org/{doi}" if doi else (f" URL: {url}" if url else "")
        out += [f'<a id="ref-{number}"></a>', f"## [{number}] {title or key}", "",
                f"- Tác giả: {author or 'Không có trường tác giả trong BibTeX.'}",
                f"- Năm: {year or 'Không có trường năm trong BibTeX.'}",
                f"- Nguồn: {venue or 'Không có trường nguồn trong BibTeX.'}{links}",
                f"- Trạng thái audit: `{audit.get(key, 'BIB_PENDING')}`", ""]
    return "\n".join(out).rstrip() + "\n"


def manifest_pages(source_root: Path, manifest_path: Path) -> dict[str, str]:
    manifest = load_manifest(manifest_path)
    entries = manifest["pages"]
    source_to_target = {entry["source"]: entry["target"] for entry in entries}
    ref_targets = {f"../{source}": target for source, target in source_to_target.items()}
    pages: dict[str, str] = {}
    for entry in entries:
        source_rel = entry["source"]
        source = source_root / source_rel
        if not source.is_file():
            raise FileNotFoundError(f"manifest source not found: {source_rel}")
        target = entry["target"]
        if entry.get("format") == "bib":
            pages[target] = render_bib(source.read_text(encoding="utf-8"), source_root / "references/citation-audit.csv")
        else:
            pages[target] = convert_text(source.read_text(encoding="utf-8"), source_rel, target, ref_targets)
    chapter_links = [entry for entry in entries if entry["target"].startswith("course/book/ch")]
    appendix_links = [entry for entry in entries if entry["target"].startswith("course/book/appendices/")]
    index = [GENERATED.format(source="scripts/sync_manifest.json"), "# Giáo trình đầy đủ", "",
             "Đây là giáo trình đầy đủ của khóa học. Các trang mini-course trong mục **Các bài học** là bản ôn nhanh.", "",
             "## Đề cương", "", "- [Đề cương tự học](syllabus)", "", "## Các chương", ""]
    for entry in chapter_links:
        label = entry["target"].rsplit("/", 1)[-1].removesuffix(".md").upper()
        index.append(f"- [{label}]({entry['target'].rsplit('/', 1)[-1].removesuffix('.md')})")
    index += ["", "## Phụ lục", ""]
    for entry in appendix_links:
        slug = entry["target"].rsplit("/", 1)[-1].removesuffix(".md")
        index.append(f"- [{slug}](/course/book/appendices/{slug})")
    index += ["", "## Tham khảo", "", "- [Danh mục tham khảo](references)", ""]
    pages["course/book/index.md"] = "\n".join(index)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        default="../biomedical-rdm/docs/course-source/rdm-mini-course-source.md",
        help="canonical source markdown file",
    )
    parser.add_argument(
        "--source-root",
        default="../biomedical-rdm",
        help="canonical source repository root for manifest pages",
    )
    parser.add_argument(
        "--manifest",
        default="scripts/sync_manifest.json",
        help="manifest mapping source files to generated pages",
    )
    parser.add_argument("--check", action="store_true", help="check without writing")
    args = parser.parse_args()

    source = Path(args.source)
    if not source.is_file():
        print(f"source not found: {source}", file=sys.stderr)
        return 1
    try:
        pages = parse_pages(source)
        pages.update(manifest_pages(Path(args.source_root), Path(args.manifest)))
    except (OSError, UnicodeError, ValueError, json.JSONDecodeError) as exc:
        print(f"cannot read source: {exc}", file=sys.stderr)
        return 1

    mismatches: list[str] = []
    for relative_path, expected in pages.items():
        target = Path(relative_path)
        actual = target.read_text(encoding="utf-8") if target.is_file() else None
        if actual != expected:
            mismatches.append(relative_path)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected, encoding="utf-8", newline="")

    if args.check:
        if mismatches:
            print("out of sync:")
            print("\n".join(f"- {path}" for path in mismatches))
            return 1
        print(f"OK: {len(pages)} pages are in sync")
        return 0

    print(f"synced {len(mismatches)} of {len(pages)} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
